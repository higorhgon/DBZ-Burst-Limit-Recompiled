#!/usr/bin/env python3
"""Builds the direct host resolve compute shaders into a C++ header.

The shaders (android/shaders/direct_host_resolve, from XenDroid,
github.com/rfandango/XenDroid, Xenia's BSD license) copy a resolve straight
from a host render target into guest memory, instead of first dumping the
render target into the EDRAM buffer and resolving from there. The SDK patch
(vulkan/render_target_cache.cpp) uses them when this header exists.

Needs glslangValidator and spirv-opt (Termux: pkg install glslang spirv-tools).
Only the unscaled variants are built: the Android build never scales the
resolution.

Usage: gen_direct_host_resolve.py <shader_root> <output.h>
"""

import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

WRAPPER = (
    "#version 460\n"
    "#extension GL_EXT_control_flow_attributes : require\n"
    "#extension GL_EXT_samplerless_texture_functions : require\n"
    "#extension GL_GOOGLE_include_directive : require\n"
    '#include "%s"\n'
)


def variants():
    """(identifier, entry file, defines)."""
    result = []
    for source_uint in (0, 1):
        uint = "_uint" if source_uint else ""
        for bpp in (32, 64):
            for msaa in (1, 2, 4):
                result.append((
                    f"resolve_host_color{uint}_{bpp}bpp_{msaa}xmsaa_cs",
                    "resolve_host_color_entry.xesli",
                    [f"XE_RESOLVE_HOST_COLOR_BPP={bpp}",
                     f"XE_RESOLVE_HOST_COLOR_MSAA_SAMPLES={msaa}",
                     f"XE_RESOLVE_HOST_COLOR_SOURCE_UINT={source_uint}"]))
        for bpp in (8, 16, 32, 64, 128):
            for msaa in (1, 2, 4):
                result.append((
                    f"resolve_host_color_full{uint}_{bpp}bpp_{msaa}xmsaa_cs",
                    "resolve_host_color_full_entry.xesli",
                    [f"XE_RESOLVE_HOST_COLOR_FULL_DEST_BPP={bpp}",
                     f"XE_RESOLVE_HOST_COLOR_MSAA_SAMPLES={msaa}",
                     f"XE_RESOLVE_HOST_COLOR_SOURCE_UINT={source_uint}"]))
    for msaa in (1, 2, 4):
        result.append((f"resolve_host_depth_32bpp_{msaa}xmsaa_cs",
                       "resolve_host_depth_entry.xesli",
                       [f"XE_RESOLVE_HOST_DEPTH_MSAA_SAMPLES={msaa}"]))
    return result


def sources_digest(shader_dir):
    digest = hashlib.sha256()
    digest.update(open(__file__, "rb").read())
    for root, _, files in sorted(os.walk(shader_dir)):
        for name in sorted(files):
            if name.endswith(".xesli"):
                digest.update(name.encode())
                digest.update(open(os.path.join(root, name), "rb").read())
    return digest.hexdigest()


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 1
    shader_dir = os.path.join(sys.argv[1], "gpu", "shaders")
    output = sys.argv[2]
    digest = sources_digest(sys.argv[1])
    stamp = "// sources: " + digest + "\n"
    if os.path.isfile(output):
        with open(output) as f:
            if f.readline() == stamp:
                print("direct host resolve shaders: up to date")
                return 0
    for tool in ("glslangValidator", "spirv-opt"):
        if not shutil.which(tool):
            print(f"error: {tool} not found (pkg install glslang spirv-tools)",
                  file=sys.stderr)
            return 1
    lines = [stamp,
             "// Generated by scripts/gen_direct_host_resolve.py, don't edit.\n",
             "#pragma once\n#include <cstdint>\n\n",
             "#define REX_HAVE_DIRECT_HOST_RESOLVE_SHADERS 1\n\n",
             "namespace rex::graphics::vulkan::direct_host_resolve_shaders {\n"]
    with tempfile.TemporaryDirectory() as tmp:
        for ident, entry, defines in variants():
            raw = os.path.join(tmp, ident + ".raw.spv")
            opt = os.path.join(tmp, ident + ".spv")
            cmd = ["glslangValidator", "--stdin", "-DSHADING_LANGUAGE_GLSL_XE=1",
                   "-S", "comp", "-V", "-I" + shader_dir, "-o", raw]
            cmd += ["-D" + d for d in defines]
            r = subprocess.run(cmd, input=WRAPPER % entry, text=True,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if r.returncode != 0:
                print(f"error: glslangValidator failed for {ident}:\n{r.stdout}",
                      file=sys.stderr)
                return 1
            r = subprocess.run(["spirv-opt", "-O", raw, "-o", opt],
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                               text=True)
            if r.returncode != 0:
                print(f"error: spirv-opt failed for {ident}:\n{r.stdout}",
                      file=sys.stderr)
                return 1
            data = open(opt, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little")
                     for i in range(0, len(data), 4)]
            lines.append(f"inline constexpr uint32_t {ident}[] = {{\n")
            for i in range(0, len(words), 12):
                lines.append(",".join(f"0x{w:x}" for w in words[i:i + 12]) + ",\n")
            lines.append("};\n")
    lines.append("}  // namespace rex::graphics::vulkan::direct_host_resolve_shaders\n")
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    partial = output + ".part"
    with open(partial, "w") as f:
        f.writelines(lines)
    os.replace(partial, output)
    print(f"direct host resolve shaders: built {len(variants())} into {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
